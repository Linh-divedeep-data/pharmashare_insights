#!/usr/bin/env bash
# Bootstrap Sprint 0 (Project Setup & DevOps Foundation) for a new project.
# Mirrors bd epic vietdist-analytics-platform-8op (S0.1-S0.7 / Jira VDAP-166).
# Idempotent: safe to re-run, skips steps whose output already exists.
#
# Usage:
#   bin/bootstrap-sprint0.sh [target-dir]
#
# target-dir defaults to current directory. Script cd's into it and runs
# all steps there.

set -euo pipefail

TARGET_DIR="${1:-.}"
cd "$TARGET_DIR"
TARGET_DIR="$(pwd)"

log() { echo "[bootstrap-sprint0] $*"; }
skip() { echo "[bootstrap-sprint0] skip: $*"; }

# ---------------------------------------------------------------------------
# S0.1 — Repo Skeleton & Dependency Management
# ---------------------------------------------------------------------------

if [ -d .git ]; then
  skip "git repo already initialized"
else
  log "git init"
  git init
fi

if [ -f pyproject.toml ]; then
  skip "pyproject.toml already exists"
else
  log "uv init"
  uv init --no-workspace
fi

log "uv add core deps (polars, google client libs, dotenv, fastexcel, pytest)"
uv add polars google-api-python-client google-auth-httplib2 google-auth-oauthlib \
  python-dotenv fastexcel pytest

log "create data lake + src/tests/config skeleton"
mkdir -p data/raw data/bronze data/silver data/gold src/extract src/transform tests config
for d in data/raw data/bronze data/silver data/gold; do
  touch "$d/.gitkeep"
done
touch src/__init__.py src/extract/__init__.py config/__init__.py

# ---------------------------------------------------------------------------
# S0.2 — Secrets & Environment Config
# ---------------------------------------------------------------------------

if [ -f .gitignore ]; then
  skip ".gitignore already exists"
else
  log "write .gitignore baseline"
  cat > .gitignore <<'EOF'
# Secrets — never commit
credentials.json
.env

# Data lake output — keep folder structure (.gitkeep) but never commit data files
data/raw/*
data/bronze/*
data/silver/*
data/gold/*
!data/raw/.gitkeep
!data/bronze/.gitkeep
!data/silver/.gitkeep
!data/gold/.gitkeep

# macOS
.DS_Store

# Logs
*.log

# Python
.venv/
__pycache__/
EOF
fi

if [ -f .env.example ]; then
  skip ".env.example already exists"
else
  log "write .env.example placeholder"
  cat > .env.example <<'EOF'
GOOGLE_SERVICE_ACCOUNT_JSON=credentials.json
GDRIVE_FOLDER_ID=your-google-drive-folder-id
EOF
fi

log "reminder: place real credentials.json + .env manually (never generated by script)"

# ---------------------------------------------------------------------------
# S0.3 — CI Pipeline Skeleton
# ---------------------------------------------------------------------------

if [ -f .github/workflows/ci.yml ]; then
  skip ".github/workflows/ci.yml already exists"
else
  log "write .github/workflows/ci.yml"
  mkdir -p .github/workflows
  cat > .github/workflows/ci.yml <<'EOF'
name: CI

on:
  push:
    branches: ["**"]
  pull_request:
    branches: ["**"]

jobs:
  lint-test:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Install uv
        uses: astral-sh/setup-uv@v6

      - name: Install dependencies
        run: uv sync

      - name: Lint
        run: uvx ruff check .
        continue-on-error: true

      - name: Test
        run: uv run pytest --collect-only
EOF
fi

# ---------------------------------------------------------------------------
# S0.5 — Logging & Observability Skeleton
# ---------------------------------------------------------------------------

if [ -f src/logger.py ]; then
  skip "src/logger.py already exists"
else
  log "write src/logger.py"
  cat > src/logger.py <<'EOF'
"""Shared logging module (Sprint 0 / S0.5).

Every pipeline module should log through get_logger(batch_id) instead of
configuring its own logging.Logger, so all output shares one format:
"%(asctime)s [%(levelname)s] [batch_id=...] %(message)s".
"""

import logging

_LOG_FORMAT = "%(asctime)s [%(levelname)s] [batch_id=%(batch_id)s] %(message)s"
_LOGGER_NAME = "app"
_HANDLER_NAME = "app-handler"


def get_logger(batch_id: str) -> logging.LoggerAdapter:
    """Return a logger adapter that stamps every log line with batch_id."""
    logger = logging.getLogger(_LOGGER_NAME)
    if not any(h.name == _HANDLER_NAME for h in logger.handlers):
        handler = logging.StreamHandler()
        handler.name = _HANDLER_NAME
        handler.setFormatter(logging.Formatter(_LOG_FORMAT))
        logger.addHandler(handler)
        logger.setLevel(logging.INFO)
        logger.propagate = False
    return logging.LoggerAdapter(logger, {"batch_id": batch_id})
EOF
fi

# ---------------------------------------------------------------------------
# S0.4 — Dependency Vulnerability Scan Baseline
# ---------------------------------------------------------------------------

mkdir -p docs
BASELINE_FILE="docs/security_baseline_$(date +%Y%m%d).txt"
if ls docs/security_baseline_*.txt >/dev/null 2>&1; then
  skip "security baseline already exists ($(ls docs/security_baseline_*.txt | head -1))"
else
  log "run pip-audit, save baseline to $BASELINE_FILE"
  uvx pip-audit > "$BASELINE_FILE" 2>&1 || true
fi

# ---------------------------------------------------------------------------
# S0.7 — Branching & Commit Convention
# ---------------------------------------------------------------------------

if [ -f CONTRIBUTING.md ]; then
  skip "CONTRIBUTING.md already exists"
else
  log "write CONTRIBUTING.md"
  cat > CONTRIBUTING.md <<'EOF'
# Contributing

## Branch naming

Pattern: `<type>/<TICKET-ID>-<slug>`

- `type` — one of: `feature`, `chore`, `hotfix`, `bugfix`
- `TICKET-ID` — the ticket key, e.g. `PROJ-42`
- `slug` — lowercase, words separated by `-`, no spaces or uppercase

Branch from `develop` (not `main` and not another in-progress feature branch)
unless you're continuing work you already claimed.

## Commit messages

Follow [Conventional Commits](https://www.conventionalcommits.org/):
`<type>(PROJ-<key>): <imperative summary>` when tied to a ticket, or
`<type>: <summary>` when it isn't.

Valid types: `feat`, `fix`, `docs`, `test`, `chore`, `ci`, `refactor`.

## Pull requests

Title: same format as commits — `<type>(PROJ-<key>): <imperative summary>`.

Body: two sections, `## Summary` (bullet points of what changed) and
`## Test plan` (checklist of what was verified).
EOF
fi

# ---------------------------------------------------------------------------
# S0.6 — README Setup Instructions
# ---------------------------------------------------------------------------

if [ -f README.md ] && grep -q "## Getting Started" README.md; then
  skip "README.md already has Getting Started section"
else
  log "append Getting Started section to README.md"
  touch README.md
  cat >> README.md <<'EOF'

## Getting Started

1. Clone the repo.
2. Copy `.env.example` to `.env` and fill in real values.
3. Place your `credentials.json` (Google Service Account) at repo root — it is git-ignored.
4. `uv sync`
5. `uv run python -c "import polars"` — should exit with no error.
6. Run the pipeline locally per the CLI entrypoint's `--help`.

### Common errors

- Missing `credentials.json` / `.env` vars: pipeline should fail with a clear
  error naming the missing variable, not a raw traceback.
EOF
fi

# ---------------------------------------------------------------------------
# Wrap up
# ---------------------------------------------------------------------------

log "done. Review changes with: git -C '$TARGET_DIR' status"
log "then commit manually (script does not auto-commit)."
